#!/usr/bin/env bash
# Harness registry shared by authoring, validation and sync. Add native paths and generation here.
set -euo pipefail
# shellcheck disable=SC2034 # native paths are consumed by callers sourcing the registry
harness() { # <name>: sets instruction, skills and plugins capability; rejects unknown adapters
  case "$1" in
    claude-code) instruction=CLAUDE.md; instruction_template=templates/workspace/CLAUDE.md; skills=.claude/skills; plugins=claude ;;
    codex) instruction=AGENTS.md; instruction_template=templates/harnesses/codex/AGENTS.md; skills=.agents/skills; plugins=none ;;
    *) echo "harness: unknown harness '$1'" >&2; return 1 ;;
  esac
}
skill_path() { # <source kind: skills|workspace-inherit> <relative path>: native destination
  case "$1/$2" in
    skills/*) echo "$skills/$2" ;;
    workspace-inherit/.claude/skills/*) echo "$skills/${2#.claude/skills/}" ;;
    *) echo "$2" ;;
  esac
}
generate_harness() { # <main checkout> <workspace folder> <workspace checkout>
  local adapter
  adapter=$(awk '/^harness:/ { print $2; exit }' "$3/workspace.yml")
  harness "$adapter" || return 1
  if [ "$plugins" = claude ]; then
    (cd "$1" && bash ci/plugins.sh yml "$2" "$3/workspace.yml") >"$3/workspace.yml.new" || return 1
    mv "$3/workspace.yml.new" "$3/workspace.yml"
    mkdir -p "$3/.claude"
    (cd "$1" && bash ci/plugins.sh settings "$2" "$3/workspace.yml") >"$3/.claude/settings.json" || return 1
  else
    rm -f "$3/.claude/settings.json" # generated by the previous adapter, never workspace-owned
    if awk '/^plugins:/ { s = 1; next } /^[^[:space:]#]/ { s = 0 } s && /^[[:space:]]+-/ { found = 1 } END { exit !found }' "$3/workspace.yml"; then
      echo "harness: $adapter does not support Delphi plugin sets" >&2; return 1
    fi
  fi
}
