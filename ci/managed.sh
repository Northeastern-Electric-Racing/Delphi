#!/usr/bin/env bash
# Ownership helpers shared by main-side rendering and branch sync; no harness or source-format logic.
set -euo pipefail
# shellcheck disable=SC2034 # sourced by render.sh and sync.sh
generated=workspace.generated

optouts() { # read a workspace.yml on stdin
  awk '/^opt-out:/ { s = 1; next } /^[^[:space:]#]/ { s = 0 }
    s && /^[[:space:]]+-[[:space:]]+/ { sub(/^[[:space:]]+-[[:space:]]+/, ""); sub(/[[:space:]]*#.*$/, ""); sub(/\/$/, ""); print }'
}

opted_out() { # <path> <space-separated opt-outs>
  local out
  for out in $2; do case "$1/" in "$out"/*) return 0 ;; esac; done
  return 1
}

recorded() { # <path> <records>: exact managed ownership, including files retired by a topology change
  printf '%s\n' "$2" | awk -F'\t' -v p="$1" '$2 == p { found = 1 } END { exit !found }'
}

safe_path() {
  case "$1" in '' | /* | *[!A-Za-z0-9._/-]* | */ | *//* ) return 1 ;; esac
  case "/$1/" in */../* | */./* | */.git/*) return 1 ;; esac
}

generated_records() { # ledger on stdin: validate and print records; mode blob<TAB>destination<TAB>source
  local meta path source extra
  while IFS=$'\t' read -r meta path source extra; do
    case "$meta" in '' | '#'* ) continue ;; esac
    if ! printf '%s\n' "$meta" | grep -Eq '^(100644|100755) [0-9a-f]{40}([0-9a-f]{24})?$' ||
      ! safe_path "$path" || ! safe_path "$source" || [ -n "$extra" ]; then
      echo "generated: invalid ownership record" >&2; return 1
    fi
    case "$path" in workspace.yml | workspace.generated | .delphi | .delphi/*)
      echo "generated: protected destination $path" >&2; return 1 ;;
    esac
    printf '%s\t%s\t%s\n' "$meta" "$path" "$source"
  done
}

ledger() { # <revision:path>: missing ledgers are allowed for pre-render workspaces
  local contents
  contents=$(git show "$1" 2>/dev/null || true)
  printf '%s\n' "$contents" | generated_records
}

ledger_header() { printf '# Generated by ci/render.sh; edit shared sources or opt out in workspace.yml.\n'; }
